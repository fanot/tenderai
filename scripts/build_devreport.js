const run = (text, o = {}) => new TextRun({ text, font: FONT, size: SIZE, ...o });

const P = (text, o = {}) =>
  new Paragraph({
    alignment: o.align || AlignmentType.LEFT,
    spacing: { line: LINE, after: o.after ?? 0, lineRule: LineRuleType.AUTO },
    children: Array.isArray(text) ? text : [run(text, o)],
  });

// Ячейка таблицы: строки текста передаются массивом
function cell(lines, { head = false, width, align = AlignmentType.LEFT } = {}) {
  const arr = Array.isArray(lines) ? lines : [lines];
  return new TableCell({
    width: { size: width, type: WidthType.DXA },
    shading: head ? { type: ShadingType.CLEAR, fill: "F2EDFE" } : undefined,
    margins: { top: 60, bottom: 60, left: 90, right: 90 },
    verticalAlign: VerticalAlign.TOP,
    children: arr.map((t) => {
      // элемент вида {text, link} превращается в кликабельную гиперссылку
      const kids =
        t && typeof t === "object" && t.link
          ? [
              ...(t.text ? [new TextRun({ text: t.text, font: FONT, size: CELL })] : []),
              new ExternalHyperlink({
                link: t.link,
                children: [
                  new TextRun({
                    text: t.label || t.link,
                    font: FONT,
                    size: CELL,
                    style: "Hyperlink",
                    color: "0563C1",
                    underline: {},
                  }),
                ],
              }),
            ]
          : [new TextRun({ text: String(t), font: FONT, size: CELL, bold: head })];
      return new Paragraph({
        alignment: align,
        spacing: { line: 240, lineRule: LineRuleType.AUTO },
        children: kids,
      });
    }),
  });
}

