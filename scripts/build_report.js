/** Строка содержания с отточием и номером страницы справа */
function TOCLINE(level, title) {
  const page = TOC_MAP[title] !== undefined ? String(TOC_MAP[title]) : "0";
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: { left: level === 2 ? INDENT : 0 },
    spacing: { line: 300 },
    tabStops: [{ type: TabStopType.RIGHT, position: CONTENT_W, leader: LeaderType.DOT }],
    children: [
      // кегль строк содержания уменьшен на один пункт, чтобы длинные
      // наименования разделов умещались в одну строку
      run(title, { size: 26 }),
      new TextRun({ font: FONT, size: 26, children: [new Tab()] }),
      run(page, { size: 26 }),
    ],
  });
}

// ---------- вспомогательные функции ----------
const run = (text, o = {}) => new TextRun({ text, font: FONT, size: SIZE, ...o });

/** Обычный абзац основного текста */
function P(text, o = {}) {
  return new Paragraph({
    alignment: o.align || AlignmentType.JUSTIFIED,
    indent: o.noIndent ? undefined : { firstLine: INDENT },
    spacing: { line: LINE, after: o.after ?? 0 },
    children: Array.isArray(text) ? text : [run(text, o.runOpts || {})],
  });
}

/** Заголовок структурного элемента: по центру, прописными, с новой страницы */
function HS(text, { first = false } = {}) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    alignment: AlignmentType.CENTER,
    spacing: { line: LINE, after: 240 },
    pageBreakBefore: !first,
    children: [run(text.toUpperCase(), { bold: true })],
  });
}

/** Заголовок раздела основной части: с абзацного отступа, с новой страницы */
function H1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    alignment: AlignmentType.LEFT,
    indent: { firstLine: INDENT },
    spacing: { line: LINE, after: 200 },
    pageBreakBefore: true,
    children: [run(text, { bold: true })],
  });
}

/** Заголовок подраздела */
function H2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    alignment: AlignmentType.LEFT,
    indent: { firstLine: INDENT },
    spacing: { line: LINE, before: 200, after: 120 },
    children: [run(text, { bold: true })],
  });
}

/** Маркированный элемент перечисления (по ГОСТ — с тире) */
function DASH(text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { firstLine: INDENT },
    spacing: { line: LINE },
    children: [run("– " + text)],
  });
}

/** Иллюстрация с подрисуночной подписью */
function FIG(file, caption, wPx, hPx) {
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      // межстрочный интервал явно переведён в режим «множитель»: иначе
      // унаследованное значение обрезает изображение по высоте строки
      spacing: { before: 200, after: 100, line: 240, lineRule: LineRuleType.AUTO },
      children: [
        new ImageRun({
          type: "png",
          data: fs.readFileSync(path.join(IMG, file)),
          transformation: { width: wPx, height: hPx },
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 240, line: LINE },
      children: [run(caption)],
    }),
  ];
}

/** Таблица с наименованием над ней (слева, без абзацного отступа) */
function TBL(caption, headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const scale = CONTENT_W / total;
  const cols = widths.map((w) => Math.round(w * scale));

  const cell = (text, { head = false, align = AlignmentType.LEFT } = {}, i) =>
    new TableCell({
      width: { size: cols[i], type: WidthType.DXA },
      shading: head ? { type: ShadingType.CLEAR, fill: "F2EDFE" } : undefined,
      margins: { top: 60, bottom: 60, left: 100, right: 100 },
      children: [
        new Paragraph({
          alignment: align,
          spacing: { line: 240 },
          children: [new TextRun({ text, font: FONT, size: 24, bold: head })],
        }),
      ],
    });

  return [
    new Paragraph({
      alignment: AlignmentType.LEFT,
      spacing: { before: 200, after: 80, line: LINE },
      children: [run(caption)],
    }),
    new Table({
      columnWidths: cols,
      width: { size: CONTENT_W, type: WidthType.DXA },
      borders: {
        top: { style: BorderStyle.SINGLE, size: 4, color: "999999" },
        bottom: { style: BorderStyle.SINGLE, size: 4, color: "999999" },
        left: { style: BorderStyle.SINGLE, size: 4, color: "999999" },
        right: { style: BorderStyle.SINGLE, size: 4, color: "999999" },
        insideHorizontal: { style: BorderStyle.SINGLE, size: 4, color: "BBBBBB" },
        insideVertical: { style: BorderStyle.SINGLE, size: 4, color: "BBBBBB" },
      },
      rows: [
        new TableRow({
          tableHeader: true,
          children: headers.map((h, i) => cell(h, { head: true }, i)),
        }),
        ...rows.map(
          (r) => new TableRow({ children: r.map((c, i) => cell(String(c), {}, i)) })
        ),
      ],
    }),
    new Paragraph({ spacing: { after: 200 }, children: [] }),
  ];
}

