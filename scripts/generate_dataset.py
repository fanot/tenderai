def money(lo: int, hi: int) -> float:
    val = random.uniform(lo, hi)
    step = 1000 if val < 1_000_000 else 10_000
    return round(round(val / step) * step, 2)


def money_lognormal(lo: int, hi: int) -> float:
    """Лог-равномерное распределение НМЦК в диапазоне [lo, hi]."""
    val = math.exp(random.uniform(math.log(lo), math.log(hi)))
    step = 1000 if val < 1_000_000 else 10_000
    return round(round(val / step) * step, 2)


