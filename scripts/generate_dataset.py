def make_customer(category: str) -> str:
    pref = random.choice(CATEGORY_PREFIX.get(category, CUSTOMER_PREFIX))
    pool = CATEGORY_CUSTOMERS.get(category, []) * 3 + CUSTOMER_NAME
    name = random.choice(pool).format(n=random.randint(1, 25))
    return f'{pref} "{name}"'


def build(n: int = 480) -> list[dict]:
    today = date(2026, 8, 18)
    out: list[dict] = []
    for i in range(n):
        cat, okpd, templates, (lo, hi) = random.choices(CATEGORIES, weights=CATEGORY_WEIGHTS)[0]
        region_code, region = random.choices(REGIONS, weights=REGION_WEIGHTS)[0]
        law = random.choices(LAWS, weights=[0.65, 0.35])[0]
        published = today - timedelta(days=random.randint(0, 45))
        deadline = published + timedelta(days=random.randint(7, 40))
        status = (
            "Подача заявок" if deadline >= today
            else random.choices(STATUSES[1:], weights=[0.3, 0.62, 0.08])[0]
        )
        # НМЦК распределена лог-нормально: мелких закупок значительно больше крупных,
        # как и на реальном рынке госзаказа.
        nmck = money_lognormal(lo, hi)
        subject = random.choice(templates).format(obj=random.choice(OBJECTS))
        pool = CATEGORY_REQUIREMENTS[cat]
        reqs = random.sample(pool, k=random.randint(1, min(2, len(pool)))) + random.sample(
            COMMON_REQUIREMENTS, k=random.randint(1, 2)
        )
        adv_pool = list(ADVANTAGES)
        if cat != "ИТ и разработка ПО":
            adv_pool = [a for a in adv_pool if "программного обеспечения" not in a]
        adv = random.choice(adv_pool)
        reg_no = f"{random.choice('03')}{random.randint(10**10, 10**11 - 1)}"

        description = (
            f"{subject}. Закупка проводится в соответствии с {law}. "
            f"Способ определения поставщика: {random.choice(PROCEDURES)}. "
            f"{random.choice(DELIVERY)} {random.choice(PAYMENT)} "
            f"Требования к участникам: {' '.join(reqs)} "
            + (f"{adv} " if adv else "")
            + f"Место поставки: {region}. Код ОКПД2: {okpd}."
        )

        out.append(
            {
                "id": f"T-{i + 1:04d}",
                "registry_number": reg_no,
                "subject": subject,
                "description": description,
                "law": law,
                "procedure": random.choice(PROCEDURES),
                "platform": random.choice(PLATFORMS),
                "customer": make_customer(cat),
                "customer_inn": str(random.randint(7700000000, 7799999999)),
                "region": region,
                "region_code": region_code,
                "category": cat,
                "okpd2": okpd,
                "nmck": nmck,
                "currency": "RUB",
                "application_security_pct": random.choice([0, 0.5, 1, 2]),
                "contract_security_pct": random.choice([0, 5, 10, 30]),
                "published_at": published.isoformat(),
                "deadline_at": deadline.isoformat(),
                "status": status,
                "smp_only": adv.startswith("Преимущества субъектам малого"),
                "requirements": reqs,
                "advantages": adv,
                "url": f"https://zakupki.gov.ru/epz/order/notice/view/common-info.html?regNumber={reg_no}",
            }
        )
    return out


if __name__ == "__main__":
    data = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Записано {len(data)} тендеров -> {OUT}")
